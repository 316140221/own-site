import fs from "node:fs";
import path from "node:path";
import { normalizePathPrefix, stripQueryAndHash, toPosixPath } from "./lib/path.mjs";
import { readJsonOrDefaultSync } from "./lib/json.mjs";

const rootDir = process.cwd();
const distDir = path.resolve(rootDir, process.argv[2] || "dist");
const headersPath = path.join(distDir, "_headers");
const manifestPath = path.resolve(rootDir, "build/asset-manifest.json");

function readManifest() {
  return readJsonOrDefaultSync(manifestPath, null);
}

function ensureDist() {
  if (!fs.existsSync(distDir)) {
    fs.mkdirSync(distDir, { recursive: true });
  }
}

function buildHeaderLines(manifest) {
  const immutableTtlRaw = manifest && Number(manifest.immutableTtlSeconds);
  const immutableTtl =
    Number.isFinite(immutableTtlRaw) && immutableTtlRaw >= 0 ? immutableTtlRaw : 31536000;
  const entries = (manifest && manifest.entries) || {};
  const prefix = normalizePathPrefix();
  const prefixTrimmed = prefix === "/" ? "" : prefix.replace(/\/$/, "");

  function withPrefix(pathPattern) {
    const value = String(pathPattern || "").trim();
    if (!value) return value;
    if (prefixTrimmed && value.startsWith("/")) return `${prefixTrimmed}${value}`;
    return value;
  }
  const headerLines = [];

  headerLines.push("# generated by scripts/post-build-cache.mjs");
  headerLines.push(`# PATH_PREFIX=${prefix}`);
  headerLines.push(`# immutableTtlSeconds=${immutableTtl}`);
  if (manifest && manifest.generatedAt) {
    headerLines.push(`# assetManifestGeneratedAt=${String(manifest.generatedAt)}`);
  }
  headerLines.push("");

  headerLines.push(
    withPrefix("/*"),
    "  Cache-Control: public,max-age=300",
    ""
  );

  const hashedAssets = Array.from(
    new Set(
      Object.values(entries)
        .map((value) => String(stripQueryAndHash(value) || "").trim())
        .map((value) => (value.startsWith("/") ? value : `/${value}`))
        .map((value) => {
          const idx = value.indexOf("/assets/");
          return idx !== -1 ? value.slice(idx) : value;
        })
        .filter((value) => value.startsWith("/assets/"))
        .filter(Boolean)
    )
  ).sort((a, b) => a.localeCompare(b));

  if (hashedAssets.length) {
    for (const assetPath of hashedAssets) {
      headerLines.push(
        withPrefix(assetPath),
        `  Cache-Control: public,max-age=${immutableTtl},immutable`,
        ""
      );
    }
  } else {
    headerLines.push(
      withPrefix("/assets/*"),
      `  Cache-Control: public,max-age=${immutableTtl},immutable`,
      ""
    );
  }

  headerLines.push(
    withPrefix("/pagefind/*"),
    "  Cache-Control: public,max-age=604800,immutable",
    ""
  );

  return headerLines.join("\n").trimEnd() + "\n";
}

function main() {
  ensureDist();
  const manifest = readManifest();
  const content = buildHeaderLines(manifest);
  fs.writeFileSync(headersPath, content);
  console.log(`[post-build-cache] Wrote headers to ${toPosixPath(headersPath)}`);
}

main();
